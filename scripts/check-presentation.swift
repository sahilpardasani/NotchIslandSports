import Combine
import Foundation
import IslandCore

@main struct PresentationChecks {
    @MainActor static func main() {
        let name = "NotchPresentationChecks." + UUID().uuidString
        let defaults = UserDefaults(suiteName: name)!
        defer { defaults.removePersistentDomain(forName: name) }
        let model = IslandPresentation(defaults: defaults)
        var count = 0
        func check(_ condition: Bool, _ label: String) { precondition(condition, label); count += 1 }
        var publications = 0
        let subscription = model.objectWillChange.sink { publications += 1 }
        model.update(sports: true, music: true, clock: true, calendar: true)
        let initial = publications
        for _ in 0..<100 { model.update(sports: true, music: true, clock: true, calendar: true) }
        check(publications == initial, "Unchanged availability must not schedule another layout update")
        check(model.selection.tertiary == .clock && model.showsSecondary && model.showsTertiary, "Three live activities")
        model.handleDrag(horizontal: -40, vertical: 0)
        check(model.collapsedActivity == .music && !model.expanded && model.selection.primary == .sports, "Quick swipe shows media without making a small score")
        check(!model.showsSecondary && model.showsTertiary, "Main media does not duplicate its companion pill; timer remains")
        model.handleDrag(horizontal: -40, vertical: 0)
        check(model.selection.primary == .sports && model.collapsedActivity == .calendar && !model.expanded, "Compact swipe browses Calendar without shrinking sports")
        model.handleDrag(horizontal: 40, vertical: 0)
        check(model.selection.primary == .sports, "Opposite swipe returns")
        model.handleDrag(horizontal: 40, vertical: 0)
        let slots = model.selection
        model.handleDrag(horizontal: 40, vertical: 0)
        check(!model.expanded && model.collapsedActivity == .calendar && model.selection == slots, "Calendar swipe stays compact, preserves all slots")
        let calendarOpen = publications
        for _ in 0..<100 { model.update(sports: true, music: true, clock: true, calendar: false) }
        check(publications == calendarOpen && model.selectedTab == .calendar, "Event changes never steal page or re-layout")
        model.pullDown()
        check(model.expanded && model.selectedTab == .calendar, "Pull down explicitly opens agenda")
        model.collapse()
        check(model.selection == slots && model.collapsedActivity == .calendar, "Collapse returns to compact Calendar")
        model.cyclePrimary()
        check(model.collapsedActivity == .sports, "Swipe leaves Calendar for sports")
        model.handleDrag(horizontal: -45, vertical: 2, held: true)
        check(model.merged && !model.expanded && !model.showsSecondary && !model.showsTertiary, "Held swipe merges")
        check(model.selection == slots, "Held gesture does not also cycle the primary")
        model.update(sports: true, music: true, clock: true, calendar: true)
        check(model.merged && !model.showsSecondary, "Provider refresh cannot undo merge")
        check(IslandPresentation(defaults: defaults).merged, "Merge preference survives restart")
        model.handleDrag(horizontal: -40, vertical: 0)
        check(model.selection.primary == .sports && model.merged, "Merged swipe never demotes sports")
        model.handleDrag(horizontal: 45, vertical: 0, held: true)
        check(model.showsSecondary && model.showsTertiary, "Menu restores all live slots")
        check(!IslandPresentation(defaults: defaults).merged, "Split preference persists")
        model.open(.clock)
        model.update(sports: true, music: true, clock: false)
        check(model.selectedTab == .clock && model.expanded, "Keep unavailable Clock guidance open")
        model.collapse()
        model.update(sports: false, music: false, clock: false, calendar: true)
        check(model.selection.primary == nil && !model.showsSecondary && !model.showsTertiary, "Calendar alone never creates live activity")
        let empty = publications
        for _ in 0..<100 { model.update(sports: false, music: false, clock: false, calendar: true) }
        check(publications == empty, "Empty state must not loop")
        model.cyclePrimary()
        check(!model.expanded && model.collapsedActivity == .calendar, "Compact Calendar reachable with no live activities")
        model.collapse()
        model.update(sports: true, music: false, clock: true, calendar: true)
        check(model.selection.tertiary == nil, "Calendar doesn't make a third satellite")
        model.handleDrag(horizontal: 0, vertical: 40)
        check(model.expanded && model.pinned, "Pull-down pins expansion")
        model.handleDrag(horizontal: 0, vertical: -40)
        check(!model.expanded && !model.pinned, "Push-up collapses")
        model.handleDrag(horizontal: 2, vertical: 40, held: true)
        check(!model.merged && !model.expanded, "Held vertical drag doesn't accidentally merge")
        model.handleDrag(horizontal: -10, vertical: 0, held: true)
        check(!model.merged, "Small drag doesn't merge")
        model.update(sports: true, music: false, clock: false)
        model.update(sports: true, music: true, clock: false)
        check(model.selection.primary == .sports && model.selection.secondary == .music && model.showsSecondary,
              "A newly observed browser video splits from the existing sports activity")
        model.open(.music)
        check(model.expanded && model.selectedTab == .music, "Media satellite opens its control panel")
        model.expandedContentMounted = true
        model.open(.clock)
        model.collapse()
        check(model.contentActivity == .clock && model.expandedContentMounted, "Closing retains the visible page instead of flashing the primary")
        model.open(.music)
        check(model.contentActivity == .music && model.expanded, "Reversing a close uses the new page")
        model.finishResize()
        check(model.expandedContentMounted, "A stale close must not unmount a reopened panel")
        model.collapse(); model.finishResize()
        check(!model.expandedContentMounted && model.closingTab == nil, "Settled collapse releases expanded content")
        model.open(.music)
        model.update(sports: true, music: false, clock: false)
        check(!model.expanded && !model.showsSecondary && model.selection.primary == .sports, "Session ending merges and closes the media panel")
        model.setMerged(true)
        model.update(sports: true, music: true, clock: false)
        check(model.showsSecondary && model.selection.secondary == .music, "A new playback session splits again after the previous session was merged")
        model.update(sports: true, music: true, clock: true, approval: true)
        check(model.selection.primary == .sports && model.selection.secondary == .music && model.collapsedActivity == .approval, "Approval uses main attention page, not a split slot")
        check(model.selection.tertiary == .clock && model.selection.overflow.isEmpty, "Only media and Clock occupy companion slots")
        model.secondaryFits = false; model.tertiaryFits = false
        check(model.collapsedActivity == .approval && !model.expanded, "Crowded menu exposes urgent request in main notch without opening it")
        check(model.selection.primary == .sports, "Urgent fallback preserves the user's primary selection")
        model.pullDown()
        check(model.expanded && model.selectedTab == .approval, "Pull down on fallback opens the actual pending request")
        model.open(.music)
        model.update(sports: true, music: true, clock: true, approval: true)
        check(model.selectedTab == .music, "Hidden approval does not replace expanded controls under the pointer")
        model.collapse(); model.finishResize()
        model.secondaryFits = true; model.tertiaryFits = true
        check(model.collapsedActivity == .approval && model.showsSecondary, "Approval stays visible when satellite room returns")
        model.mergeActivities()
        check(model.collapsedActivity == .approval, "Merging cannot hide a pending approval")
        model.update(sports: true, music: true, clock: true, approval: false)
        check(model.collapsedActivity == .sports && model.merged, "Clearing request restores merged score")
        model.update(sports: true, music: true, clock: true, approval: true)
        model.open(.approval)
        model.update(sports: true, music: true, clock: false, approval: true)
        check(model.expanded && model.selectedTab == .approval, "Score/timer changes never steal approval under review")
        model.update(sports: true, music: true, clock: true, approval: false)
        check(model.selection.secondary == .music && model.selection.tertiary == .clock, "Resolving approvals restores ordinary slots")
        model.promote(.music)
        check(model.expanded && model.selectedTab == .music && model.selection.primary == .sports, "Media controls open without demoting sports")
        model.collapse(); model.finishResize()
        check(model.collapsedActivity == .sports && model.selection.secondary == .music, "Closing media restores large score")
        model.promote(.clock); model.collapse(); model.finishResize()
        check(model.collapsedActivity == .sports && model.selection.tertiary == .clock, "Closing Clock restores large score")
        model.mergeActivities()
        model.update(sports: true, music: false, clock: false)
        model.update(sports: true, music: false, clock: true)
        check(model.selection.primary == .sports && model.selection.secondary == .clock && model.showsSecondary, "New native timer splits beside sports")
        model.update(sports: false, music: true, clock: true)
        model.promote(.music); model.collapse(); model.finishResize()
        check(model.collapsedActivity == .music, "Without sports, media may occupy main island")
        model.update(sports: true, music: true, clock: true)
        check(model.collapsedActivity == .sports && model.selection.secondary != .sports && model.selection.tertiary != .sports, "Sports returning from media-only state reclaims main island")
        let stable = model.selection
        for _ in 0..<21 { model.cyclePrimary() }
        check(model.selection == stable, "Repeated collapsed swipes cannot move sports into a pill")
        model.cyclePrimary()
        check(model.collapsedActivity == .music, "Both native music apps share the media browse page")
        model.pullDown(); model.collapse()
        check(model.collapsedActivity == .music, "Opening and closing media preserves explicit browse choice")
        model.handleDrag(horizontal: 45, vertical: 0, held: true)
        check(model.collapsedActivity == .sports && model.showsSecondary && model.showsTertiary && !model.merged, "Hold-and-swipe tucks main media into its small pill and restores full score")
        model.cyclePrimary(); model.setMerged(true); model.toggleSplitGesture()
        check(model.collapsedActivity == .sports && !model.merged && model.showsSecondary, "Held swipe restores media pill even from merged media page")
        model.cyclePrimary()
        let mediaPublications = publications
        model.update(sports: true, music: true, clock: true)
        check(model.collapsedActivity == .music && publications == mediaPublications, "Score updates cannot steal the chosen media page")
        model.update(sports: true, music: false, clock: true)
        check(model.collapsedActivity == .sports && !model.compactMedia, "Media ending returns to the score")
        model.update(sports: true, music: true, clock: true)
        model.observeClock([.init(id: "tea", paused: true)], fresh: true)
        model.mergeActivities(); model.open(.clock)
        model.observeClock([.init(id: "tea", paused: false)], fresh: false)
        check(model.merged && model.expanded, "A stale/failed native read cannot pretend Resume succeeded")
        model.observeClock([.init(id: "tea", paused: false)], fresh: true)
        check(!model.merged && !model.expanded && model.showsSecondary && model.showsTertiary,
              "Confirmed native Resume restores all three activities and closes Clock controls")
        check(model.selection.primary == .sports && model.collapsedActivity == .sports, "Resume leaves the score large")
        model.finishResize(); model.mergeActivities()
        let resumedPublications = publications
        for _ in 0..<100 { model.observeClock([.init(id: "tea", paused: false)], fresh: true) }
        check(model.merged && publications == resumedPublications, "Countdown refreshes neither undo a deliberate merge nor trigger layouts")
        model.observeClock([.init(id: "tea", paused: true)], fresh: true)
        check(model.merged, "Pausing alone does not force a split")
        model.open(.sports)
        model.observeClock([.init(id: "tea", paused: false)], fresh: true)
        check(model.expanded && model.selectedTab == .sports && !model.merged, "External Resume leaves expanded score open")
        model.observeClock([.init(id: "tea", paused: true), .init(id: "coffee", paused: false)], fresh: true)
        model.mergeActivities(); model.open(.approval)
        model.observeClock([.init(id: "tea", paused: false), .init(id: "coffee", paused: false)], fresh: true)
        check(!model.merged && model.expanded && model.selectedTab == .approval, "One of several timers resumes without stealing approval under review")
        model.observeClock([], fresh: true); model.mergeActivities(); model.open(.clock)
        model.observeClock([.init(id: "tea", paused: false)], fresh: true)
        check(model.expanded, "A newly discovered running timer is not a false resume transition")
        model.observeClock([.init(id: "tea", paused: true)], fresh: true)
        model.observeClock([.init(id: "other", paused: false)], fresh: true)
        check(model.expanded && model.merged, "Replacing a timer with the same count is not resuming the old identity")
        model.update(sports: true, music: true, clock: true)
        model.collapse(); model.setMerged(false)
        let companionSlots = model.selection
        model.open(.music)
        check(companionSlots.secondary == .music ? !model.showsSecondary : !model.showsTertiary, "Expanded media hides its artwork companion")
        check(companionSlots.secondary == .clock ? model.showsSecondary : model.showsTertiary, "Expanded media leaves the timer companion visible")
        model.collapse()
        check(model.showsSecondary && model.showsTertiary && model.selection == companionSlots, "Closing media returns both pills to their original slots")
        model.open(.clock)
        check(companionSlots.secondary == .clock ? !model.showsSecondary : !model.showsTertiary, "Expanded Clock hides its timer companion")
        check(companionSlots.secondary == .music ? model.showsSecondary : model.showsTertiary, "Expanded Clock leaves artwork visible")
        model.collapse()
        check(model.showsSecondary && model.showsTertiary && model.selection == companionSlots, "Closing Clock returns both pills without reordering")
        withExtendedLifetime(subscription) {}
        print("Passed \(count) presentation checks, including persistent merge, Calendar browsing and no repeated layout publications.")
    }
}
